package Lessons1.Analitics;

public abstract class TextMetrics {
    protected int countLine;
    protected int countWord;
    protected int countSim;

    public int getcountLine(){
        return this.countLine;
}
    public int getcountWord(){
        return this.countWord;
    }
    public int getcountSim(){
        return this.countSim;
    }
}
